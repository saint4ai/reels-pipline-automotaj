const clean = results.filter(Boolean)
const kept = []
for (const r of clean) {
  const drop = new Set((r.verdict?.dropped || []).map((s) => s.toLowerCase().trim()))
  for (const src of r.findings.sources || []) {
    const isDropped = [...drop].some((d) => src.name.toLowerCase().includes(d) || d.includes(src.name.toLowerCase().split(' ')[0]))
    if (!isDropped) kept.push({ lens: r.lens, ...src })
  }
}
log(`Источников выжило: ${kept.length}`)
return { kept, notes: clean.map((r) => ({ lens: r.lens, notes: r.findings.notes, why: r.verdict?.why })) }
