export const meta = {
  name: 'podcast-clip-mining',
  description: 'Разметить подкаст по спикерам и найти цепляющие фрагменты со скорингом',
  phases: [
    { title: 'Разбор', detail: 'три агента делят транскрипт, размечают спикеров и находят фрагменты' },
    { title: 'Скоринг', detail: 'оценка каждого фрагмента по цепляемости' },
  ],
}

const S = '/private/tmp/claude-501/-Users-miso-Desktop-onAI-Workspace/5f7b46c2-9c03-4c94-99af-c99907a46826/scratchpad'

const CHUNKS = [
  { key: 'p1', from: 0, to: 1600, label: 'начало — знакомство, кого уволят, что такое вайбкодинг' },
  { key: 'p2', from: 1550, to: 3100, label: 'середина — применение в бизнесе, кейсы, деньги' },
  { key: 'p3', from: 3050, to: 4600, label: 'финал — рынок, безопасность, будущее, выводы' },
]

const CLIPS = {
  type: 'object',
  required: ['clips'],
  properties: {
    clips: {
      type: 'array',
      items: {
        type: 'object',
        required: ['start_sec', 'end_sec', 'speaker', 'topic', 'hook_line', 'full_text', 'why_strong'],
        properties: {
          start_sec: { type: 'number', description: 'Начало фрагмента в секундах от начала подкаста — по границе смысла, не по таймеру' },
          end_sec: { type: 'number', description: 'Конец — мысль должна быть закончена' },
          speaker: { type: 'string', enum: ['автор', 'гость', 'ведущая', 'диалог'], description: 'Кто говорит основную часть фрагмента' },
          topic: { type: 'string', description: 'Тема в 2-4 словах' },
          hook_line: { type: 'string', description: 'Самая цепляющая фраза внутри фрагмента, дословно' },
          full_text: { type: 'string', description: 'Текст фрагмента целиком' },
          why_strong: { type: 'string', description: 'Почему это зацепит: дерзкое заявление / практический инсайт / объявление' },
          kind: { type: 'string', enum: ['дерзкое заявление', 'практический инсайт', 'объявление', 'история', 'цифра'] },
        },
      },
    },
  },
}

const SCORE = {
  type: 'object',
  required: ['score', 'title', 'breakdown', 'verdict'],
  properties: {
    score: { type: 'number', description: 'Итоговый балл 0–100' },
    title: { type: 'string', description: 'Продающий заголовок для имени файла: цепляющий, конкретный, БЕЗ двоеточий и спецсимволов, до 60 знаков' },
    breakdown: { type: 'string', description: 'По каждому критерию — сколько баллов и почему' },
    verdict: { type: 'string', enum: ['брать', 'запас', 'выбросить'] },
    weak_spot: { type: 'string', description: 'Что мешает: обрыв мысли, нужен контекст, вода в начале' },
  },
}

const found = await pipeline(
  CHUNKS,
  (c) => agent(
    `Разбери часть подкаста и найди фрагменты, которые сработают как отдельные вертикальные рилсы.

ИСХОДНЫЕ ДАННЫЕ:
Пословный транскрипт с таймингами: \`${S}/podcast_words.json\` — массив {t: секунды, w: слово}.
Читай его питоном, бери слова с индексами ${c.from}–${c.to}. Это часть: ${c.label}.
Полный связный текст для понимания контекста: \`~/Desktop/onAI-Workspace/projects/podcast_ai_2026/TRANSCRIPT.md\`

УЧАСТНИКИ (различать по содержанию речи):
— **Автор** — владелец онлайн-школы onAI Academy, вайбкодер. Говорит про свою платформу,
  академию, что был не разработчиком и научился за год, про агентов, навыки, безопасность,
  про то, что собирает продукты на естественном языке. Говорит «я разработчик, до этого вообще
  не знал программирования».
— **Гость** — маркетолог, 8 лет в платном трафике, Facebook/Google/YouTube, строил отделы маркетинга.
— **Ведущая** — ведущая, задаёт вопросы, представляет гостей, говорит «я являюсь ученицей Автора».

ЗАДАЧА: найти в своей части 8–14 фрагментов, каждый из которых:
1. **Длится 25–70 секунд.** Короче — не раскроет мысль, длиннее — не досмотрят.
2. **Начинается и заканчивается по границе смысла.** Не по таймеру. Мысль должна быть целой:
   зритель без контекста подкаста должен понять, о чём речь. Проверь по тексту, что первая фраза
   не начинается с «и вот поэтому», а последняя не обрывается на середине.
3. **Содержит крючок** — фразу, ради которой стоит смотреть.

ЧТО ИСКАТЬ (методика нарезки, проверенная на прошлых партиях):
— **дерзкие заявления** — то, с чем хочется поспорить или что звучит вызывающе;
— **практические инсайты** — конкретное «как» с деталями, а не общие слова;
— **объявления** — «сейчас происходит вот что», описание сдвига на рынке;
— **истории** — личный кейс с началом и концом;
— **цифры** — суммы, сроки, количества с объяснением.

ЧТО НЕ БРАТЬ: приветствия, представления участников, благодарности, вежливые переходы,
общие рассуждения без конкретики, фрагменты, где непонятно без предыдущих 5 минут.

Тайминги указывай ТОЧНО по данным из podcast_words.json — по ним будет резаться видео.

Следуй Karpathy-guidelines: не выдумывай фрагменты, каждый должен реально быть в транскрипте.`,
    { label: `разбор:${c.key}`, phase: 'Разбор', schema: CLIPS }
  ),
  (res, c) => {
    if (!res || !res.clips?.length) return null
    return parallel(res.clips.map((clip) => () =>
      agent(
        `Оцени фрагмент подкаста как кандидата в вертикальный рилс.

ТЕМА: ${clip.topic}
ГОВОРИТ: ${clip.speaker}
ТИП: ${clip.kind || '—'}
ХУК: «${clip.hook_line}»
ДЛИТЕЛЬНОСТЬ: ${Math.round(clip.end_sec - clip.start_sec)} с
ТЕКСТ ЦЕЛИКОМ:
${clip.full_text}

ОЦЕНИ ПО ПЯТИ КРИТЕРИЯМ, каждый до 20 баллов:

1. **Крючок в первые 3 секунды** — зацепит ли первая фраза при пролистывании ленты.
   20 — останавливает скролл. 0 — начинается с «ну вот».
2. **Самодостаточность** — понятно ли без контекста подкаста. 20 — да. 0 — нужны предыдущие 5 минут.
3. **Конкретность** — есть ли цифры, имена, детали, шаги. 20 — да. 0 — общие слова.
4. **Эмоция или спор** — вызывает ли реакцию: несогласие, узнавание, тревогу, интерес.
5. **Законченность** — есть ли вывод. 20 — мысль закрыта. 0 — обрывается.

ЗАТЕМ ПРИДУМАЙ ЗАГОЛОВОК для имени файла. Правила (утверждены заказчиком):
— цепляющий, ассоциативный с содержанием, вызывает желание посмотреть;
— конкретика важнее абстракции, можно цифру или факт из фрагмента;
— БЕЗ двоеточий и спецсимволов — это имя файла;
— без жаргона разработчиков;
— до 60 знаков.
Примеры одобренных ранее: «Роботы пришли не за руками — за дипломами»,
«2 миллиона бизнесов в Казахстане ждут твоё решение», «В Тредсе ищут вайбкодеров».

ВЕРДИКТ: «брать» от 70 баллов, «запас» 50–69, «выбросить» ниже 50.

Будь строг. Лучше десять сильных фрагментов, чем сорок средних.`,
        { label: `скоринг:${clip.topic.slice(0, 22)}`, phase: 'Скоринг', schema: SCORE }
      ).then((sc) => (sc ? { ...clip, ...sc } : null))
    ))
  }
)

const all = found.flat().filter(Boolean)
const ranked = all.sort((a, b) => b.score - a.score)
const mine = ranked.filter((c) => c.speaker === 'автор')
const общие = ranked.filter((c) => c.speaker !== 'автор')
log(`Всего фрагментов: ${ranked.length} · Автор: ${mine.length} · остальные: ${общие.length}`)
log(`Брать: ${ranked.filter((c) => c.verdict === 'брать').length}`)
return { alexander: mine, others: общие }
