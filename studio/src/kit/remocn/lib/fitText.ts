const ADV_FALLBACK = 0.9607;

// letterSpacing в Reel.tsx
const TRACKING_EM = -0.01;

/** Ширина строки в em при заданном трекинге. */
const widthEm = (text: string) =>
  [...text].reduce((sum, ch) => sum + (ADV[ch] ?? ADV_FALLBACK), 0) +
  TRACKING_EM * Math.max(0, text.length - 1);

/**
 * Кегль, при котором слово влезает в maxWidth.
 * При базовом кегле почти ничего не ужимается — ужимаются только
 * самые длинные слова («ПРЕДПРИНИМАТЕЛЬ»), чтобы не уехать за кадр.
 */
export const fitFontSize = (text: string, baseSize: number, maxWidth: number) => {
  const w = widthEm(text);
  if (w <= 0) return baseSize;
  return Math.min(baseSize, maxWidth / w);
};
